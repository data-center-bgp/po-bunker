#!/usr/bin/env python3
"""One-off export of the PO Bunker master data from the CGA Supabase project into a
single SQL file for the new Postgres (see DEPLOY.md, "Move the data").

It only READS Supabase (`db query --read-only`) and writes import.sql, which you
review and then apply on the VPS. Run it from a folder that is already linked to the
project (`npx supabase link`), for example the one the earlier Supabase work used:

    python deploy/import/export_supabase.py --workdir path/to/linked/folder --out import.sql

What is copied: categories, business units, units of measure, vessel types, regions,
and the companies, partners, products and code budgets that are not test data (name
starting with "ZZ"). Orders, users and files are not copied: there are no real orders
yet, users are created with the admin CLI, and company logos are uploaded again from
the company form (logo_path is left empty on purpose).

import.sql refuses to run unless the target tables are empty, so it cannot be applied twice.
"""
import argparse
import json
import subprocess
import sys

# (table, filter on the Supabase side, columns to blank out). Order matters: parents first.
TABLES = [
    ("product_categories", "true", []),
    ("business_units", "true", []),
    ("uoms", "true", []),
    ("vessel_types", "true", []),
    ("code_budgets", "name not like 'ZZ%'", []),
    ("regions", "true", []),
    ("companies", "name not like 'ZZ%'", ["logo_path"]),
    ("vessels", "true", []),
    ("partners", "name not like 'ZZ%'", []),
    ("products", "name not like 'ZZ%'", []),
]

TAG = "$po_import$"


def query(workdir, sql):
    proc = subprocess.run(
        ["npx", "supabase@latest", "db", "query", "--linked", "--read-only", sql],
        cwd=workdir,
        capture_output=True,
        text=True,
        shell=(sys.platform == "win32"),
    )
    out = proc.stdout
    start = out.find("{")
    if proc.returncode != 0 or start < 0:
        sys.exit("supabase query failed:\n" + proc.stdout + proc.stderr)
    return json.loads(out[start:])["rows"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workdir", required=True, help="folder linked to the Supabase project")
    ap.add_argument("--out", default="import.sql")
    args = ap.parse_args()

    parts = []
    counts = {}
    for table, where, blank in TABLES:
        rows = query(
            args.workdir,
            f"select coalesce(jsonb_agg(to_jsonb(t) order by t.id), '[]'::jsonb) as j "
            f"from po_bunker.{table} t where {where}",
        )
        data = rows[0]["j"]
        if isinstance(data, str):
            data = json.loads(data)
        counts[table] = len(data)
        if not data:
            continue
        for row in data:
            for col in blank:
                row[col] = None
        cols = list(data[0].keys())
        payload = json.dumps(data, ensure_ascii=False)
        if TAG in payload:
            sys.exit(f"{table}: data contains the dollar-quote tag, pick another")
        collist = ", ".join(cols)
        parts.append(
            f"-- {table}: {len(data)} rows\n"
            f"INSERT INTO {table} ({collist}) OVERRIDING SYSTEM VALUE\n"
            f"SELECT {collist} FROM jsonb_populate_recordset(NULL::{table}, {TAG}{payload}{TAG}::jsonb);\n"
            f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), (SELECT max(id) FROM {table}));\n"
        )

    guard_tables = ", ".join(f"'{t}'" for t, _, _ in TABLES)
    guard = (
        "DO $guard$\nDECLARE t text; n bigint;\nBEGIN\n"
        f"  FOR t IN SELECT unnest(ARRAY[{guard_tables}]) LOOP\n"
        "    EXECUTE format('SELECT count(*) FROM %I', t) INTO n;\n"
        "    IF n > 0 THEN RAISE EXCEPTION 'table % is not empty: this import was already applied', t; END IF;\n"
        "  END LOOP;\nEND\n$guard$;\n"
    )
    with open(args.out, "w", encoding="utf8", newline="\n") as f:
        f.write("-- Generated by deploy/import/export_supabase.py. Apply once on an empty database.\n")
        f.write("BEGIN;\n" + guard + "\n" + "\n".join(parts) + "\nCOMMIT;\n")

    print(f"wrote {args.out}")
    for table, n in counts.items():
        print(f"  {table:20} {n}")


if __name__ == "__main__":
    main()
